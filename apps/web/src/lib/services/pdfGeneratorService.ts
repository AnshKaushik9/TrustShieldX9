// --- Utility: Cross-Environment UUID Generator ---
function generateUUID(): string {
  if (typeof crypto !== 'undefined' && crypto.randomUUID) {
    return crypto.randomUUID();
  }
  if (typeof crypto !== 'undefined' && crypto.getRandomValues) {
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    return (1e7.toString() + -1e3 + -4e3 + -8e3 + -1e11).replace(/[018]/g, (c: any) =>
      (c ^ (crypto.getRandomValues(new Uint8Array(1))[0] & (15 >> (c / 4)))).toString(16)
    );
  }
  return 'xxxxxxxx-xxxx-4xxx-yxxx-xxxxxxxxxxxx'.replace(/[xy]/g, function (c) {
    const r = (Math.random() * 16) | 0,
      v = c === 'x' ? r : (r & 0x3) | 0x8;
    return v.toString(16);
  });
}

// --- Utility: Calculate SHA256 ---
async function calculateSHA256(file: File): Promise<string> {
  if (typeof crypto === 'undefined' || !crypto.subtle || !crypto.subtle.digest) {
    return "Unavailable (requires HTTPS)";
  }
  try {
    const arrayBuffer = await file.arrayBuffer();
    const hashBuffer = await crypto.subtle.digest('SHA-256', arrayBuffer);
    const hashArray = Array.from(new Uint8Array(hashBuffer));
    const hashHex = hashArray.map(b => b.toString(16).padStart(2, '0')).join('');
    return hashHex;
  } catch (err) {
    return "Unavailable (hash calculation failed)";
  }
}

// --- Utility: Extract Frame/Image ---
async function extractMediaBytes(file: File): Promise<{ bytes: Uint8Array, type: 'png' | 'jpeg' } | null> {
  if (file.type.startsWith('image/')) {
    const arrayBuffer = await file.arrayBuffer();
    return {
      bytes: new Uint8Array(arrayBuffer),
      type: file.type === 'image/png' ? 'png' : 'jpeg'
    };
  } else if (file.type.startsWith('video/')) {
    return new Promise((resolve) => {
      const video = document.createElement('video');
      video.autoplay = false;
      video.muted = true;
      video.playsInline = true;
      const url = URL.createObjectURL(file);
      video.src = url;

      video.onloadeddata = () => {
        // seek to 1 second or start
        video.currentTime = Math.min(1, video.duration || 0);
      };

      video.onseeked = () => {
        const canvas = document.createElement('canvas');
        canvas.width = video.videoWidth;
        canvas.height = video.videoHeight;
        const ctx = canvas.getContext('2d');
        if (ctx) {
          ctx.drawImage(video, 0, 0, canvas.width, canvas.height);
          const dataUrl = canvas.toDataURL('image/jpeg', 0.8);
          // Convert base64 to Uint8Array
          const base64Data = dataUrl.split(',')[1];
          const binaryString = window.atob(base64Data);
          const len = binaryString.length;
          const bytes = new Uint8Array(len);
          for (let i = 0; i < len; i++) {
            bytes[i] = binaryString.charCodeAt(i);
          }
          URL.revokeObjectURL(url);
          resolve({ bytes, type: 'jpeg' });
        } else {
          URL.revokeObjectURL(url);
          resolve(null);
        }
      };

      video.onerror = () => {
        URL.revokeObjectURL(url);
        resolve(null);
      };
    });
  }
  return null;
}

// --- Utility: Draw Footer ---
function drawFooter(page: PDFPage, font: PDFFont, pageNum: number) {
  const { width } = page.getSize();
  page.drawText('Generated by TrustShield AI | Hackathon Demo', {
    x: 50,
    y: 30,
    size: 10,
    font,
    color: rgb(0.5, 0.5, 0.5),
  });
  page.drawText(`Page ${pageNum}`, {
    x: width - 80,
    y: 30,
    size: 10,
    font,
    color: rgb(0.5, 0.5, 0.5),
  });
}

// --- Main Service ---
export const pdfGeneratorService = {
  generateAndDownloadReport: async (report: ForensicsReport, file: File) => {
    try {
      const doc = await PDFDocument.create();
      const font = await doc.embedFont(StandardFonts.Helvetica);
      const boldFont = await doc.embedFont(StandardFonts.HelveticaBold);

      let pageNum = 1;
      let page = doc.addPage([595.28, 841.89]); // A4
      const { width, height } = page.getSize();

      const themeColor = rgb(0.2, 0.4, 0.8);
      const textColor = rgb(0.1, 0.1, 0.1);
      const textLight = rgb(0.4, 0.4, 0.4);

      // --- 1. Cover Page & Header ---
      page.drawText('TrustShield AI', { x: 50, y: height - 50, size: 24, font: boldFont, color: themeColor });
      page.drawText('AI Media Forensics Report', { x: 50, y: height - 80, size: 18, font, color: textColor });

      page.drawText(`Report ID: ${generateUUID()}`, { x: 50, y: height - 120, size: 10, font, color: textLight });
      page.drawText(`Job ID: ${report.jobId}`, { x: 50, y: height - 135, size: 10, font, color: textLight });
      page.drawText(`Generated: ${new Date().toLocaleString()}`, { x: 50, y: height - 150, size: 10, font, color: textLight });

      // --- 8. Final Verdict (Prominent Box on Cover) ---
      const isManipulated = (report.humanValidation?.finalDecision || report.riskBadge) !== "Authentic";
      const finalBadge = report.humanValidation?.finalDecision || report.riskBadge;
      const verdictBg = isManipulated ? rgb(1, 0.9, 0.9) : rgb(0.9, 1, 0.9);
      const verdictBorder = isManipulated ? rgb(0.8, 0, 0) : rgb(0, 0.6, 0);

      page.drawRectangle({
        x: width / 2, y: height - 165, width: width / 2 - 50, height: 100,
        color: verdictBg, borderColor: verdictBorder, borderWidth: 1
      });
      page.drawText(`Verdict: ${finalBadge}`, { x: width / 2 + 15, y: height - 90, size: 14, font: boldFont, color: verdictBorder });
      page.drawText(`Authenticity Score: ${report.authenticityScore}%`, { x: width / 2 + 15, y: height - 110, size: 12, font: boldFont, color: textColor });
      page.drawText(`Confidence: ${report.confidence}%`, { x: width / 2 + 15, y: height - 130, size: 12, font, color: textColor });
      page.drawText(`Action: ${isManipulated ? 'Quarantine' : 'Safe'}`, { x: width / 2 + 15, y: height - 150, size: 12, font: boldFont, color: verdictBorder });

      let currentY = height - 200;

      // --- HITL Validation Section ---
      if (report.humanValidation) {
        page.drawText('Human-in-the-Loop Validation', { x: 50, y: currentY, size: 12, font: boldFont, color: themeColor });
        currentY -= 15;
        page.drawText(`AI Decision: ${report.humanValidation.originalAiDecision}`, { x: 50, y: currentY, size: 10, font, color: textColor });
        currentY -= 15;

        let humanValidationText = "No";
        if (report.humanValidation.decisionAction === "Approve") {
          humanValidationText = "Approved by Analyst";
        } else if (report.humanValidation.decisionAction === "Reject") {
          humanValidationText = `Rejected by Analyst (Modified to ${report.humanValidation.finalDecision})`;
        } else if (report.humanValidation.decisionAction === "Override") {
          humanValidationText = `Overridden (Modified to ${report.humanValidation.finalDecision})`;
        }

        page.drawText(`Human Validation: ${humanValidationText}`, { x: 50, y: currentY, size: 10, font, color: textColor });
        currentY -= 15;
        page.drawText(`Reviewer: ${report.humanValidation.reviewer}`, { x: 50, y: currentY, size: 10, font, color: textColor });
        currentY -= 15;
        page.drawText(`Review Time: ${new Date(report.humanValidation.reviewTime).toLocaleString()}`, { x: 50, y: currentY, size: 10, font, color: textColor });
        currentY -= 15;

        if (report.humanValidation.isReviewed && report.humanValidation.reviewerNotes) {
          page.drawText(`Reviewer Notes: ${report.humanValidation.reviewerNotes}`, { x: 50, y: currentY, size: 10, font, color: textColor });
          currentY -= 15;
        }
        currentY -= 10;
      }

      // --- 2. Media Preview ---
      const mediaData = await extractMediaBytes(file);
      if (mediaData) {
        page.drawText('Media Preview', { x: 50, y: currentY, size: 14, font: boldFont, color: themeColor });
        currentY -= 20;

        let image;
        if (mediaData.type === 'png') {
          image = await doc.embedPng(mediaData.bytes);
        } else {
          image = await doc.embedJpg(mediaData.bytes);
        }

        const imgDims = image.scaleToFit(width - 100, 200);
        page.drawImage(image, {
          x: 50,
          y: currentY - imgDims.height,
          width: imgDims.width,
          height: imgDims.height,
        });
        currentY -= (imgDims.height + 40);
      }

      // --- 3. Executive Summary ---
      page.drawText('Executive Summary', { x: 50, y: currentY, size: 14, font: boldFont, color: themeColor });
      currentY -= 20;

      const summaryLines = report.explanation.summary.match(/.{1,90}(\s|$)/g) || [report.explanation.summary];
      summaryLines.forEach(line => {
        page.drawText(line.trim(), { x: 50, y: currentY, size: 11, font, color: textColor });
        currentY -= 15;
      });
      currentY -= 20;

      drawFooter(page, font, pageNum);

      // --- NEW PAGE ---
      page = doc.addPage([595.28, 841.89]);
      pageNum++;
      currentY = height - 50;

      // --- 6. Technical Metadata ---
      const hash = await calculateSHA256(file);
      page.drawText('Technical Metadata', { x: 50, y: currentY, size: 14, font: boldFont, color: themeColor });
      currentY -= 25;

      const metaKeys = [
        { label: 'File Name', val: file.name },
        { label: 'File Size', val: report.metadata.fileSize },
        { label: 'File Type', val: file.type },
        { label: 'Resolution', val: report.metadata.resolution || 'N/A' },
        { label: 'Duration', val: report.metadata.duration || 'N/A' },
        { label: 'SHA-256 Hash', val: hash },
      ];

      metaKeys.forEach(m => {
        page.drawText(`${m.label}:`, { x: 50, y: currentY, size: 10, font: boldFont, color: textColor });
        page.drawText(m.val, { x: 150, y: currentY, size: 10, font, color: textLight });
        currentY -= 15;
      });
      currentY -= 20;

      // --- 4 & 5. Detailed Analysis & Breakdown ---
      page.drawText('Confidence Breakdown & Metrics', { x: 50, y: currentY, size: 14, font: boldFont, color: themeColor });
      currentY -= 25;

      const metrics = [
        { name: 'Facial Analysis', score: report.breakdown.facialAnalysis, desc: 'Evaluates structural consistency of facial landmarks.' },
        { name: 'Metadata Integrity', score: report.breakdown.metadataIntegrity, desc: 'Checks for manipulation in EXIF and structural atoms.' },
        { name: 'Compression Analysis', score: report.breakdown.compressionAnalysis, desc: 'Detects multiple lossy saves and error levels.' },
        { name: 'Temporal Consistency', score: report.breakdown.temporalConsistency, desc: 'Analyzes frame-to-frame flow and physics.' },
        { name: 'GAN Artifact Detection', score: report.breakdown.ganArtifacts, desc: 'Scans for known generative adversarial network fingerprints.' },
      ];

      metrics.forEach(m => {
        page.drawText(m.name, { x: 50, y: currentY, size: 11, font: boldFont, color: textColor });
        page.drawText(`${m.score}%`, { x: 250, y: currentY, size: 11, font: boldFont, color: themeColor });

        // Progress bar background
        page.drawRectangle({ x: 300, y: currentY, width: 200, height: 10, color: rgb(0.9, 0.9, 0.9) });
        // Progress bar fill
        page.drawRectangle({ x: 300, y: currentY, width: (m.score / 100) * 200, height: 10, color: themeColor });

        currentY -= 15;
        page.drawText(m.desc, { x: 50, y: currentY, size: 9, font, color: textLight });
        currentY -= 25;
      });

      // --- 7. AI Explanation (Key Findings & Evidence) ---
      currentY -= 10;
      page.drawText('Key Findings', { x: 50, y: currentY, size: 14, font: boldFont, color: themeColor });
      currentY -= 20;

      report.explanation.keyFindings.forEach(kf => {
        page.drawText(`• ${kf}`, { x: 50, y: currentY, size: 11, font, color: textColor });
        currentY -= 15;
      });
      currentY -= 15;

      page.drawText('Technical Evidence', { x: 50, y: currentY, size: 14, font: boldFont, color: themeColor });
      currentY -= 20;
      const evidenceLines = report.explanation.evidence.match(/.{1,90}(\s|$)/g) || [report.explanation.evidence];
      evidenceLines.forEach(line => {
        page.drawText(line.trim(), { x: 50, y: currentY, size: 10, font, color: textLight });
        currentY -= 15;
      });

      drawFooter(page, font, pageNum);

      // Save and Download
      const pdfBytes = await doc.save();
      // eslint-disable-next-line @typescript-eslint/no-explicit-any
      const blob = new Blob([pdfBytes as any], { type: 'application/pdf' });
      const url = URL.createObjectURL(blob);

      const link = document.createElement('a');
      link.href = url;
      link.download = `TrustShield_Report_${report.jobId}.pdf`;
      document.body.appendChild(link);
      link.click();
      document.body.removeChild(link);
      URL.revokeObjectURL(url);


    } catch (error) {
      console.error("Failed to generate PDF:", error);
      throw new Error("Failed to generate the PDF report. Please try again.");
    }
  }
};
